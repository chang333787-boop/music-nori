export const cellById = id => CELLS.find(c => c.id === id) || null;
export const FIRST = CELLS.filter(c => c.first).map(c => c.id);
// 첫 판 추천 차례 — 먼저 필요한 칸을 지키되, 헷갈리는 짝(높이 ↔ 길이)이 일찍 만나게
export const ORDER = ['so3', 'so4', 'so5', 'ri1', 'ri2', 'ga1', 'ga2', 'ri4', 'ga3', 'ak1', 'ri5', 'ri6', 'ak2'];

// progress = { [id]: { stars } } · 별 1 이상 = 지남
export const passed = (progress, id) => !!(progress && progress[id] && progress[id].stars >= 1);
// 앞 칸 중 아직 안 지난 것(건너뛰고 들어오면 한 줄 안내 · 잠그지 않음)
export const missingPre = (progress, id) => (cellById(id)?.pre || []).filter(p => !passed(progress, p));
// 추천 다음 칸 — start(반 설정 시작 칸)부터 차례에서 아직 안 지난 첫 칸. 다 지났으면 null
export function nextCell(progress, start = ORDER[0]) {
  const i = Math.max(0, ORDER.indexOf(start));
  for (const id of [...ORDER.slice(i), ...ORDER.slice(0, i)]) if (!passed(progress, id)) return id;
  return null;
}
