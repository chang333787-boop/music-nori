const jongOf = w => { const c = w.charCodeAt(w.length - 1); return c >= 0xAC00 && c <= 0xD7A3 ? (c - 0xAC00) % 28 : 0; };
function josaFor(word, p) {
  const pair = JOSA.find(x => x.includes(p));
  if (!pair) return p;
  const j = jongOf(word.replace(/[’)]+$/, ''));
  if (pair[0] === '으로') return j === 0 || j === 8 ? '로' : '으로';
  return j ? pair[0] : pair[1];
}
