// 방 규칙 시험(진짜 DB · 네트워크) — 시험 방은 0000~0999(아이들 방은 1000~9999). npm run test:db
const DB = 'https://music-nori-class-default-rtdb.asia-southeast1.firebasedatabase.app';
const TS = { '.sv': 'timestamp' };
const call = async (method, path, body) => { const r = await fetch(`${DB}/${path}.json`, { method, headers: { 'content-type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }); return { ok: r.ok, status: r.status, data: await r.json().catch(() => null) }; };
let fail = 0; const check = (name, cond, info) => { if (cond) console.log('✓ ' + name); else { fail++; console.log('✗ ' + name, info ? JSON.stringify(info) : ''); } };
(async () => {
  const room = '0' + String(Math.floor(Math.random() * 1000)).padStart(3, '0');
  const tok = Math.random().toString(36).slice(2) + Math.random().toString(36).slice(2);
  let r = await call('PUT', `rooms/${room}/own`, { tok, at: TS });
  check('선생님이 방을 잡음', r.ok, r);
  r = await call('PUT', `rooms/${room}/own`, { tok: 'x'.repeat(20), at: TS });
  check('다른 사람이 같은 방을 다시 못 잡음', !r.ok, r.status);
  r = await call('GET', `rooms/${room}/own`);
  check('선생님 열쇠는 못 읽음', !r.ok, r.status);
  r = await call('PUT', `rooms/${room}/t`, { tok, pub: { cell: 'so4', phase: 'show', at: TS } });
  check('열쇠로 활동을 바꿈', r.ok, r);
  r = await call('PUT', `rooms/${room}/t`, { tok: 'y'.repeat(20), pub: { cell: 'ri6', phase: 'game', at: TS } });
  check('틀린 열쇠로는 못 바꿈', !r.ok, r.status);
  r = await call('GET', `rooms/${room}/t/pub`);
  check('아이 기기는 활동을 읽음', r.ok && r.data && r.data.cell === 'so4', r.data);
  r = await call('GET', `rooms/${room}/t/tok`);
  check('활동 쪽 열쇠도 못 읽음', !r.ok, r.status);
  r = await call('GET', `rooms/${room}/t`);
  check('활동 통째로는 못 읽음', !r.ok, r.status);
  r = await call('PUT', `rooms/${room}/res/abcd1234`, { a: 2, no: 7, c: 'so4', s: 3, k: 12, n: 12, at: TS });
  check('아이 결과를 보냄', r.ok, r);
  r = await call('PUT', `rooms/${room}/res/abcd1234`, { a: 2, no: 7, c: 'so4', s: 3, k: 12, n: 12, at: TS, name: '철수' });
  check('정해지지 않은 칸(이름 등)은 못 씀', !r.ok, r.status);
  r = await call('PUT', `rooms/${room}/res/abcd1234`, { a: 2, no: 7, c: 'so4', s: 9, k: 12, n: 12, at: TS });
  check('별 4개 이상은 못 씀', !r.ok, r.status);
  r = await call('GET', `rooms/${room}/res`);
  check('TV는 결과를 읽음', r.ok && r.data && r.data.abcd1234 && r.data.abcd1234.s === 3, r.data);
  r = await call('PUT', `rooms/9${room.slice(1)}x/own`, { tok, at: TS });
  check('네 자리 숫자가 아닌 방은 못 만듦', !r.ok, r.status);
  r = await call('GET', 'rooms');
  check('방 목록은 못 읽음', !r.ok, r.status);
  console.log(fail ? `✗ 방 규칙 시험 실패 ${fail}` : `✓ 방 규칙 시험 통과(시험 방 ${room})`);
  process.exit(fail ? 1 : 0);
})();
